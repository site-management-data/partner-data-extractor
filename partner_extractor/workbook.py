from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from typing import Mapping

import pandas as pd
from openpyxl import load_workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

from .config import Settings


def build_about_sheet(
    settings: Settings, sheets: Mapping[str, pd.DataFrame]
) -> pd.DataFrame:
    generated = datetime.now(timezone.utc).astimezone().strftime("%Y-%m-%d %H:%M %Z")
    rows = [
        ("Product", "Partner Data Extract"),
        ("Partner", settings.partner_name),
        ("Generated", generated),
        ("Data source", "Zite Manager"),
        ("Output file", settings.output_filename),
        ("Refresh method", "Automatically generated by Python"),
        ("", ""),
        ("Worksheet", "Description"),
        ("Site List", "Current partner-supported sites from the Zite site list."),
        (
            "Latest Site Assessment",
            "Most recent site-monitoring record available for each partner site.",
        ),
        ("Activity Report", "Activity submissions reported by the partner."),
        ("Activity Summary", "Automated aggregation of activity submissions."),
        (
            "Service Map",
            "Contacts and service-mapping records associated with partner sites.",
        ),
    ]
    if settings.include_referrals:
        rows.append((
            "Referrals",
            "De-identified operational referral records for partner sites. Personal identifiers, household demographics and free-text narratives are excluded.",
        ))
    if settings.include_alerts:
        rows.append(("Site Alerts", "Alert records associated with partner sites."))
    rows.extend(
        [
            ("", ""),
            ("Record counts", ""),
            *[(name, f"{len(df):,}") for name, df in sheets.items()],
        ]
    )
    return pd.DataFrame(rows, columns=["Field", "Value"])


def _safe_sheet_name(name: str) -> str:
    return name[:31]


def format_workbook(path: Path) -> None:
    workbook = load_workbook(path)
    header_fill = PatternFill("solid", fgColor="003B5C")
    header_font = Font(color="FFFFFF", bold=True)
    section_fill = PatternFill("solid", fgColor="D9EAF2")

    for sheet in workbook.worksheets:
        # About must have a minimal worksheet view. This prevents Excel from
        # reporting and repairing an invalid sheet1.xml view record.
        if sheet.title == "About":
            sheet.freeze_panes = None
            sheet.sheet_view.pane = None
            sheet.sheet_view.selection = []
            sheet.auto_filter.ref = None
        else:
            sheet.freeze_panes = "A2"
            sheet.auto_filter.ref = sheet.dimensions

        sheet.sheet_view.showGridLines = False

        for cell in sheet[1]:
            cell.fill = header_fill
            cell.font = header_font
            cell.alignment = Alignment(
                horizontal="center", vertical="center", wrap_text=True
            )

        for column_cells in sheet.columns:
            letter = get_column_letter(column_cells[0].column)
            header = str(column_cells[0].value or "").strip().casefold()
            is_date_column = "date" in header or header == "today"
            max_length = 0
            for cell in column_cells[:250]:
                value = "" if cell.value is None else str(cell.value)
                max_length = max(max_length, min(len(value), 45))
                cell.alignment = Alignment(vertical="top", wrap_text=False)
                if is_date_column and cell.row > 1 and cell.value is not None:
                    cell.number_format = "yyyy-mm-dd"
            sheet.column_dimensions[letter].width = min(
                max(max_length + 2, 10), 40
            )

        sheet.row_dimensions[1].height = 36

    about = workbook["About"]
    about.column_dimensions["A"].width = 27
    about.column_dimensions["B"].width = 75
    for row in range(2, about.max_row + 1):
        if about.cell(row, 1).value in {"Worksheet", "Record counts"}:
            for cell in about[row]:
                cell.fill = section_fill
                cell.font = Font(bold=True)

    workbook.save(path)


def write_workbook(
    sheets: dict[str, pd.DataFrame], settings: Settings
) -> Path:
    settings.output_directory.mkdir(parents=True, exist_ok=True)
    output_path = settings.output_directory / settings.output_filename

    ordered_sheets: dict[str, pd.DataFrame] = {
        "About": build_about_sheet(settings, sheets),
        **sheets,
    }

    with pd.ExcelWriter(output_path, engine="openpyxl") as writer:
        for name, dataframe in ordered_sheets.items():
            dataframe.to_excel(
                writer,
                sheet_name=_safe_sheet_name(name),
                index=False,
            )

    format_workbook(output_path)
    return output_path
